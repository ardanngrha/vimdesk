#!/usr/bin/env python3
"""Generate localized OS guides from the website's shared installation steps."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate(language, data, platform_data, platform):
    en = language == 'en'
    selected = platform_data['platforms'][platform]
    by_id = {step['id']: step for step in data['steps'] + platform_data['steps']}
    steps = [by_id[key] for key in selected['stepIds']]
    title = selected['title'][language]
    intro = ('Start here if you have never installed Neovim, Homebrew, or a terminal development tool. '
             'Follow the steps in order. No GitHub or AI account is needed for the local practice workspace.' if en else
             'Mulai di sini kalau belum pernah memasang Neovim, Homebrew, atau alat developer lewat Terminal. '
             'Ikuti langkah secara berurutan. Tidak perlu akun GitHub atau AI untuk mencoba workspace latihan lokal.')
    lines = ['<!-- Generated by scripts/build_guide.py from docs/assets/guide.json and platform-guides.json. -->', '# ' + title, '', intro, '',
             '[Interactive guide / Panduan interaktif](https://ardanngrha.github.io/vimdesk/?lang=' + language + '&os=' + platform + '#install)', '',
             selected['intro'][language], '',
             ('Requires Neovim 0.12+ and Python 3.9+.' if en else
              'Membutuhkan Neovim 0.12+ dan Python 3.9+.'), '']
    for number, step in enumerate(steps, 1):
        lines += ['## ' + str(number) + '. ' + step['title'][language], '', step['intro'][language], '']
        for block in step['blocks']:
            where = {'terminal': 'Terminal', 'powershell': 'Windows PowerShell' if en else 'PowerShell Windows',
                     'neovim': 'Inside Neovim' if en else 'Di dalam Neovim'}[block['where']]
            label = block.get('label', {}).get(language, '')
            lines += ['**' + where + (': ' + label if label else '') + '**', '',
                      '```' + {'terminal': 'sh', 'powershell': 'powershell', 'neovim': 'vim'}[block['where']], block['code'], '```', '']
        lines += ['**' + ('Success check' if en else 'Tanda berhasil') + ':** ' + step['expected'][language], '']
        if step['note']:
            lines += ['> ' + step['note'][language], '']
    lines += ['## ' + ('Platform notes' if en else 'Catatan platform'), '',
              selected['notes'][language], '',
              '## ' + ('Optional: language support and AI' if en else 'Opsional: dukungan bahasa dan AI'), '',
              ('For completion, diagnostics and formatting, install language servers from the source checkout:' if en else
               'Untuk completion, diagnostik, dan formatting, pasang language server dari folder sumber:'), '', '```sh',
              'cd "$HOME/Developer/vimdesk"', './scripts/dependencies.sh languages', '```', '',
              ('This installs servers for Go, JavaScript/TypeScript/React, Rust and Python. Projects still need their own runtimes and dependencies. '
               'Use a project-compatible Go toolchain, a Rust toolchain with Clippy, Node.js for JS/TS, and the project’s Python/venv. '
               'Follow the project’s setup instructions; the workbench does not install project packages for you.' if en else
               'Ini memasang server untuk Go, JavaScript/TypeScript/React, Rust, dan Python. Proyek tetap membutuhkan runtime dan dependensinya sendiri. '
               'Gunakan toolchain Go yang cocok dengan proyek, toolchain Rust dengan Clippy, Node.js untuk JS/TS, dan Python/venv proyek. '
               'Ikuti petunjuk setup proyek; workbench tidak memasang paket proyek otomatis.'), '',
              ('AI is optional. Install and authenticate [Codex CLI](https://github.com/openai/codex) or [Claude Code](https://code.claude.com/docs/en/overview) '
               'using their official guides. Save files, stage the changes, click Generate in Git, select an agent, and review the subject before clicking Commit. '
               'The staged diff is sent to the selected provider using your account. Normal usage limits/costs apply.' if en else
               'AI bersifat opsional. Pasang dan login [Codex CLI](https://github.com/openai/codex) atau [Claude Code](https://code.claude.com/docs/en/overview) '
               'mengikuti panduan resminya. Simpan file, stage perubahan, klik Generate di Git, pilih agent, lalu review subject sebelum klik Commit. '
               'Staged diff dikirim ke provider pilihan memakai akunmu. Batas penggunaan/biaya normal berlaku.'), '',
              ('The practice repos have no remotes. For real projects, configure a remote and authenticate with that Git hosting provider before Push/Publish. '
               'Git commit identity and remote login are different settings. See [GitHub’s first-time Git setup](https://docs.github.com/en/get-started/git-basics/set-up-git).' if en else
               'Repo latihan tidak memiliki remote. Untuk proyek sungguhan, siapkan remote dan login ke penyedia Git sebelum Push/Publish. '
               'Identitas penulis commit dan login remote adalah dua pengaturan berbeda. Lihat [setup Git pertama kali](https://docs.github.com/en/get-started/git-basics/set-up-git).'), '',
              '## ' + ('If something goes wrong' if en else 'Kalau mentok'), '']
    faqs = [
      ('brew: command not found', 'Run the exact Next steps printed by the Homebrew installer, then reopen Terminal.', 'Jalankan Next steps persis seperti yang dicetak installer Homebrew, lalu buka ulang Terminal.'),
      ('destination path already exists', 'The source was already downloaded. Use cd "$HOME/Developer/vimdesk", then git pull --ff-only and ./install.sh. Back up local edits first.', 'Sumbernya sudah pernah diunduh. Jalankan cd "$HOME/Developer/vimdesk", lalu git pull --ff-only dan ./install.sh. Simpan dulu perubahan lokal milikmu.'),
      ('vimdesk: command not found', 'Use ~/.local/bin/vimdesk, or complete the final step to add the launcher to PATH. In Windows, use the Ubuntu terminal.', 'Pakai ~/.local/bin/vimdesk, atau selesaikan langkah terakhir untuk menambahkan launcher ke PATH. Di Windows, gunakan terminal Ubuntu.'),
      ('Cannot type / tidak bisa mengetik', 'Press i to enter Insert mode. Press Esc to return to Normal mode before shortcuts or colon commands.', 'Tekan i untuk masuk Insert mode. Tekan Esc untuk kembali ke Normal mode sebelum shortcut atau perintah titik dua.'),
      ('No completion / tidak ada completion', 'LSP servers are optional. Install the relevant server and project runtime, open an actual source file, then run :checkhealth vim.lsp.', 'Server LSP bersifat opsional. Pasang server dan runtime proyek yang sesuai, buka file sumber, lalu jalankan :checkhealth vim.lsp.'),
      ('No author identity / identitas commit belum ada', 'For your own repo, configure user.name and user.email following your Git provider’s guide. The demo supplies its own local fixture identity only.', 'Untuk repo sendiri, atur user.name dan user.email mengikuti panduan penyedia Git. Demo hanya menyediakan identitas lokal untuk repo latihan.'),
    ]
    for title, english, indonesian in faqs:
        lines += ['- **' + title + ':** ' + (english if en else indonesian)]
    lines += ['', '## ' + ('Next steps' if en else 'Lanjut belajar'), '',
              '- [Editing, Git, merge conflicts and search/replace](workflow.md)',
              '- [Updates, backups, restore and uninstall](installation.md)',
              '- [Architecture](architecture.md)', '', '## ' + ('Official references' if en else 'Referensi resmi'), '']
    lines += ['- [' + source['title'] + '](' + source['url'] + ')' for source in data['sources'] + selected['sources']]
    return '\n'.join(lines) + '\n'


def main():
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument('--check', action='store_true', help='fail if generated Markdown is stale')
    args = cli.parse_args()
    data = json.loads((ROOT/'docs/assets/guide.json').read_text())
    platforms = json.loads((ROOT/'docs/assets/platform-guides.json').read_text())
    for platform, selected in platforms['platforms'].items():
        for language, filename in selected['filename'].items():
            path = ROOT/'docs'/(filename + '.md')
            content = generate(language,data,platforms,platform)
            if args.check:
                assert path.read_text() == content, 'Regenerate guide: ' + str(path)
            else:
                path.write_text(content)


if __name__ == '__main__':
    main()
